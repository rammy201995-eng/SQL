SELECT EMPLOYEE_ID,SALARY
FROM EMPLOYEES;

-- FETCH EMP WITH SALARY MORE THAN 5000
SELECT FIRST_NAME, LAST_NAME, SALARY
FROM EMPLOYEES
WHERE SALARY>5000;

-- FETCH EMP WITH SALARY RANGE OF 5000 TO 10000
SELECT FIRST_NAME, LAST_NAME, SALARY
FROM EMPLOYEES
WHERE SALARY BETWEEN 5000 AND 10000;

-- FETCH THE EMPLOYEES WORKING IN DEPARTMENT NUMBER 50
SELECT * 
FROM EMPLOYEES
WHERE DEPARTMENT_ID=50;

-- FETCH THE EMPLOYEES WORKING IN DEPARTMENT NUMBER 50,60,70
SELECT *
FROM EMPLOYEES
WHERE DEPARTMENT_ID IN (50,60,70);

-- FETCH EMPL WHOSE NAME STARTS WITH 'A' 
SELECT * 
FROM EMPLOYEES
WHERE FIRST_NAME LIKE 'A%';  -- '%'= PLACEHOLDER, 'LIKE' = THIS STATMENT IS PATTERN MATCHING STATMENT

-- FETCH EMPL WHOSE NAME ENDS WITH 'A' 
SELECT * 
FROM EMPLOYEES
WHERE FIRST_NAME LIKE '%A'; 

-- FETCH EMPL WHOSE NAME IN ANY PLACE WITH 'A' 
SELECT *
FROM EMPLOYEES
WHERE FIRST_NAME LIKE '%A%';

-- FETCH EMPLOYEE WHOSE DEPT_ID 50 AND SALARY GREATER THAN 5000 USING AND FUNCTION
SELECT *
FROM EMPLOYEES
WHERE DEPARTMENT_ID=50 AND SALARY>5000;

-- FETCH EMPLOYEE WHOSE DEPT_ID 50 AND SALARY GREATER THAN 5000 USING OR FUNCTION
SELECT *
FROM EMPLOYEES
WHERE DEPARTMENT_ID=50 OR SALARY>5000;

-- FETCH MANAGER ID IS NOT NULL
SELECT *
FROM EMPLOYEES
WHERE MANAGER_ID IS NOT NULL;

-- FETCH EMPLOYEE WHOSE RECEIVED THE COMMISSION
SELECT * 
FROM EMPLOYEES
WHERE COMMISSION_PCT IS NULL;

-- FETCH EMPLOYEE WHOSE NOT RECEIVED THE COMMISSION
SELECT * 
FROM EMPLOYEES
WHERE COMMISSION_PCT IS  NOT NULL;

-- AGGREGATION FUNCTION:
SELECT SUM(SALARY) AS TOTAL_SAL,
AVG(SALARY) AS AVG_SAL,
COUNT(*) AS EMP_COUNT,
MIN(HIRE_DATE) AS FIRST_JOINED,
MAX(HIRE_DATE) AS RECENT_JOINED
FROM EMPLOYEES;

-- GROUP BY
SELECT DEPARTMENT_ID,SUM(SALARY) AS TOTAL_SAL,
AVG(SALARY) AS AVG_SAL,
COUNT(*) AS EMP_COUNT,
MIN(HIRE_DATE) AS FIRST_JOINED,
MAX(HIRE_DATE) AS RECENT_JOINED
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID;

















 
