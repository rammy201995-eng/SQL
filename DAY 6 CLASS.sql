-- FETCH DEPARTMENT WITH MORE THAN 4 EMPLOYEES
USE HR;
SHOW TABLES;
SELECT * FROM EMPLOYEES;

SELECT DEPARTMENT_ID, COUNT(*) AS EMP_COUNT
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING EMP_COUNT>4
ORDER BY EMP_COUNT DESC
LIMIT 2
OFFSET 3;

