-- CASE AND WHEN STATEMENTS WITH EXAMPLES
USE HR;
SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, JOB_ID, CASE JOB_ID
WHEN 'AD_PRES' THEN 'PRESIDENT'
WHEN 'AD_VP' THEN 'VP'
WHEN 'IT_PROG' THEN 'PROGRAMMER'
WHEN 'SA_REP' THEN 'SALES REP'
WHEN 'FI_MGR' THEN 'FINANCE MANAGER'
ELSE 'OTHER'
END AS JOB_CATEGORY
FROM EMPLOYEES
LIMIT 15;

USE BANKINGDB;
SELECT AccountID,
       Balance,
       CASE
           WHEN Balance >= 50000 THEN 'Premium Account'
           WHEN Balance >= 25000 THEN 'Standard Account'
           ELSE 'Basic Account'
       END AS AccountCategory
FROM Accounts;








